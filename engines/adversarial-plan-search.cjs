'use strict';
// Plan-vs-counterplan stochastic game: each plan is a conditional policy
// generated from present move mechanics. No hardcoded Pokémon matchups.
// Values are based ONLY on actual Showdown terminal wins/losses/draws;
// no HP/boost/status shaping. Unresolved and untested plans are explicit.
const {buildPlans,actionForPlan}=require('./strategic-plans.cjs');
const {rng,seedFrom,mixedPolicy,sampleBernoulliWithImportance}=require('./probability-planner.cjs');
const pct=n=>Math.round(10000*n)/100;
function outcome(B){
 return !B.ended?null:B.winner==='Left'?1:B.winner==='Right'?0:0.5;
}
function preflight(B,deps,side,plans){
 return plans.map(plan=>({
  ...plan,first:actionForPlan(B,deps,side,plan,0)
 })).filter(p=>p.first);
}
function play(B,deps,left,right,seed,random,{maxTurns=65,biasChance=true}={}){
 const chance=rng(seed+':chance');
 let likelihood=1,biasCount=0,steps=0,first=null,terminal=null;
 const original=B.randomChance.bind(B);
 // Oversample at most 6 rare mechanics per play and keep the likelihood
 // ratio. Subsequent ordinary chance outcomes remain generated by Showdown.
 if(biasChance)B.randomChance=(n,d)=>{
  const p=n/d;
  if(biasCount>=6||!Number.isFinite(p)||p<=0||p>=1)return original(n,d);
  const sample=sampleBernoulliWithImportance(p,chance);
  if(sample.biased){biasCount++;likelihood*=sample.ratio}
  return sample.yes;
 };
 try{
  for(let turn=0;turn<maxTurns&&!B.ended;turn++){
   const a=actionForPlan(B,deps,'p1',left,turn);
   const b=actionForPlan(B,deps,'p2',right,turn);
   if(!a||!b)break;
   if(!first)first=[a,b];
   B.makeChoices(a,b);
   steps++;
  }
 }finally{B.randomChance=original}
 terminal=outcome(B);
 return {terminal,likelihood,steps,biased: biasCount,first,
  remaining:[B.getSide('p1').pokemon[0].hp,B.getSide('p2').pokemon[0].hp]};
}
function payoffMatrix(rows){
 return rows.map(row=>row.map(c=>
  c.weight>0?c.win/c.weight:0.5));
}
function solve(rows){
 const both=mixedPolicy(payoffMatrix(rows),320);
 return both;
}
function analyzePlans(B,deps,{budgetMs=9000,seed='plan',maxTurns=65,
 maxSamples=3200}={}){
 const started=Date.now(),deadline=started+Math.max(50,budgetMs);
 const plansL=preflight(B,deps,'p1',buildPlans(B,deps,'p1'));
 const plansR=preflight(B,deps,'p2',buildPlans(B,deps,'p2'));
 if(!plansL.length||!plansR.length)return null;
 const blob=JSON.stringify(B.toJSON()),random=rng(seed+':pairs');
 const cells=plansL.map(()=>plansR.map(()=>({
  n:0,win:0,loss:0,draw:0,weight:0,sumSq:0,
  unresolved:0,winCount:0,lossCount:0,drawCount:0,
  maxTurns:0,rare:0
 })));
 const sizes=[plansL.length,plansR.length];
 let count=0,policyL=Array(sizes[0]).fill(1/sizes[0]),
  policyR=Array(sizes[1]).fill(1/sizes[1]);
 let equilibriumRefresh=0,coverageCount=0;
 function chooseCell(){
  // Uniform sparse coverage first. Policy-guided exploration never removes
  // a candidate, even if early Monte Carlo suggests it is bad.
  if(count<sizes[0]*sizes[1]){
   const id=(count*787+251)% (sizes[0]*sizes[1]);
   // With non-coprime grid sizes use direct sequential selection.
   const cell=count;
   return [Math.floor(cell/sizes[1]),cell%sizes[1]];
  }
  if(count-equilibriumRefresh>=Math.max(18,sizes[0]+sizes[1])){
   const updated=mixedPolicy(payoffMatrix(cells),100);
   policyL=updated.left;policyR=updated.right;
   equilibriumRefresh=count;
  }
  let i,j;
  if(random()<0.55){
   // Counterplan tournament: vary our plans against opponent's
   // current best mixture to distinguish alternate win paths.
   i=Math.floor(random()*sizes[0]);
   j=draw(policyR,random);
  }else{
   i=draw(policyL,random);
   j=Math.floor(random()*sizes[1]);
  }
  return [i,j];
 }
 while(count<maxSamples&&Date.now()<deadline){
  const [i,j]=chooseCell();
  const cell=cells[i][j],trial=deps.Sim.Battle.fromJSON(blob);
  // Common chance seed keyed by pair repetition; independent from
  // candidate ID to reduce unwarranted high-variance action comparisons.
  const pairRound=cell.n;
  trial.resetRNG(seedFrom(seed+':scenario:'+pairRound));
  const result=play(trial,deps,plansL[i],plansR[j],
   seed+':scenario:'+pairRound+':'+i+':'+j,random,{maxTurns});
  cell.n++;count++;cell.maxTurns=Math.max(cell.maxTurns,result.steps);
  if(result.biased)cell.rare++;
  if(result.terminal==null){cell.unresolved++;continue}
  const w=result.likelihood;
  cell.weight+=w;cell.sumSq+=w*w;cell.win+=w*result.terminal;
  cell.loss+=w*(1-result.terminal);
  if(result.terminal===1)cell.winCount++;
  else if(result.terminal===0)cell.lossCount++;
  else cell.drawCount++;
 }
 const game=solve(cells);
 const chanceL=new Map(),chanceR=new Map();
 for(let i=0;i<plansL.length;i++)chanceL.set(plansL[i].first,
  (chanceL.get(plansL[i].first)||0)+game.left[i]);
 for(let j=0;j<plansR.length;j++)chanceR.set(plansR[j].first,
  (chanceR.get(plansR[j].first)||0)+game.right[j]);
 // Include all legal moves, even if no generated plan was able to take
 // that opener. This is useful for diagnostic comparisons.
 const actionsL=deps.legal(B,'p1'),actionsR=deps.legal(B,'p2');
 const probL=actionsL.map(a=>chanceL.get(a)||0),probR=actionsR.map(a=>chanceR.get(a)||0);
 const normalize=arr=>{const total=arr.reduce((a,b)=>a+b,0);return total>0?arr.map(x=>x/total):arr.map(()=>1/arr.length)};
 const sampled=cells.flat().filter(c=>c.n>0).length;
 const resolved=cells.flat().reduce((n,c)=>n+c.n-c.unresolved,0);
 const unfinished=cells.flat().reduce((n,c)=>n+c.unresolved,0);
 const width=sizes[0]*sizes[1];
 const summaries=plansL.map((p,i)=>{
  const row=cells[i],worst=row.filter(c=>c.n).reduce((a,c)=>{
   const val=c.weight?c.win/c.weight:0.5;
   return Math.min(a,val);
  },1);
  return {name:p.name,first:p.first,selectionPct:pct(game.left[i]),
   worstObservedWinPct:pct(worst),samples:row.reduce((v,c)=>v+c.n,0)};
 }).sort((a,b)=>b.selectionPct-a.selectionPct);
 const counter=plansR.map((p,j)=>({
  name:p.name,first:p.first,selectionPct:pct(game.right[j]),
  samples:cells.reduce((v,row)=>v+row[j].n,0)
 })).sort((a,b)=>b.selectionPct-a.selectionPct);
 return {method:'adversarial-contingent-plan-search',certified:false,
  strategyType:'scenario-counterplans-not-exact-game-value',
  leftActions:actionsL,rightActions:actionsR,
  policyLeft:normalize(probL),policyRight:normalize(probR),
  planBankLeft:plansL,planBankRight:plansR,
  planPolicyLeft:game.left,planPolicyRight:game.right,
  estimatedGameValuePct:sampled===width&&resolved>0?pct(game.value):null,
  valueBounds:[0,100],samples:count,unresolved:unfinished,
  coverage:sampled+'/'+width,planCounts:sizes,planningHorizon:maxTurns,
  elapsedMs:Date.now()-started,leadingPlans:summaries.slice(0,8),
  bestCounterplans:counter.slice(0,8),
  payoff:actionsL.map(a=>actionsR.map(b=>{
   const i=plansL.findIndex(p=>p.first===a),j=plansR.findIndex(p=>p.first===b);
   const c=i>=0&&j>=0?cells[i][j]:null;
   return {winPct:c?.weight?pct(c.win/c.weight):null,
    totalSamples:c?.n||0,unresolved:c?.unresolved||0,
    effectiveSamples:c?.sumSq?pct(c.weight*c.weight/c.sumSq)/100:0,
    estimateType:'plan-conditioned-not-optimal'}
  })),
  warning:'조건부 계획 후보끼리 실제 대전해 평가한 추정치. 상대의 모든 가능한 대응을 완전 탐색한 최적 승률이 아님.'};
}
function draw(p,random){
 let x=random();
 for(let i=0;i<p.length;i++){x-=p[i];if(x<0)return i}
 return p.length-1;
}
module.exports={preflight,play,analyzePlans};
